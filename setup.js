#!/usr/bin/env node

/**
 * Scholarship Management System Setup Script
 * 
 * This script helps set up the scholarship management system for educational institutions.
 * It guides users through the initial configuration and database setup process.
 */

const readline = require('readline');
const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');

const rl = readline.createInterface({
  input: process.stdin,
  output: process.stdout
});

console.log('🎓 Welcome to the Scholarship Management System Setup!\n');
console.log('This setup wizard will help you configure your scholarship management system for your educational institution.\n');

const questions = [
  {
    key: 'NEXT_PUBLIC_INSTITUTION_NAME',
    question: 'What is your institution\'s full name? (e.g., "University of Example"): ',
    default: 'Your University'
  },
  {
    key: 'NEXT_PUBLIC_INSTITUTION_SHORT_NAME', 
    question: 'What is your institution\'s short name/abbreviation? (e.g., "UOE"): ',
    default: 'UNI'
  },
  {
    key: 'NEXT_PUBLIC_SUPPORT_EMAIL',
    question: 'What email should students use for scholarship support? ',
    default: 'scholarships@youruniversity.edu'
  },
  {
    key: 'NEXT_PUBLIC_SUPPORT_PHONE',
    question: 'What phone number should students use for support? ',
    default: '+1-555-123-4567'
  },
  {
    key: 'DATABASE_URL',
    question: 'Enter your MongoDB connection string: ',
    default: 'mongodb://localhost:27017/scholarship_management'
  },
  {
    key: 'NEXTAUTH_SECRET',
    question: 'Enter a secure secret for authentication (press Enter to generate): ',
    default: () => generateSecureSecret()
  },
  {
    key: 'EMAIL_USERNAME',
    question: 'Enter email username for sending notifications (optional): ',
    default: ''
  },
  {
    key: 'EMAIL_PASSWORD',
    question: 'Enter email password/app password (optional): ',
    default: ''
  }
];

function generateSecureSecret() {
  return require('crypto').randomBytes(32).toString('hex');
}

async function askQuestion(question, defaultValue) {
  return new Promise((resolve) => {
    const prompt = defaultValue ? `${question}[${defaultValue}]: ` : `${question}`;
    rl.question(prompt, (answer) => {
      resolve(answer.trim() || defaultValue);
    });
  });
}

async function setupEnvironment() {
  console.log('\n📝 Setting up environment variables...\n');
  
  const envVars = {};
  
  for (const q of questions) {
    const defaultValue = typeof q.default === 'function' ? q.default() : q.default;
    envVars[q.key] = await askQuestion(q.question, defaultValue);
  }
  
  // Create .env.local file
  const envContent = Object.entries(envVars)
    .map(([key, value]) => `${key}="${value}"`)
    .join('\n');
  
  const additionalEnvVars = `

# Generated by setup script
NEXT_PUBLIC_API_URL="http://localhost:3000"
NEXTAUTH_URL="http://localhost:3000"

# Academic year configuration (MM-DD format)
NEXT_PUBLIC_ACADEMIC_YEAR_START="08-15"
NEXT_PUBLIC_ACADEMIC_YEAR_END="05-15"
NEXT_PUBLIC_DEFAULT_APPLICATION_DEADLINE="03-15"

# File upload settings
NEXT_PUBLIC_MAX_FILE_SIZE="10"
NEXT_PUBLIC_ALLOWED_FILE_TYPES="pdf,doc,docx,jpg,jpeg,png"

# Feature flags
ENABLE_STUDENT_REGISTRATION="false"
ENABLE_PUSH_NOTIFICATIONS="false"
ENABLE_ANALYTICS="false"

# System limits
MAX_APPLICATIONS_PER_STUDENT="5"
MAX_AWARD_AMOUNT="50000"
SESSION_TIMEOUT="480"
RATE_LIMIT_RPM="100"
`;

  fs.writeFileSync('.env.local', envContent + additionalEnvVars);
  console.log('✅ Environment variables saved to .env.local');
}

async function setupDatabase() {
  console.log('\n🗄️ Setting up database...\n');
  
  try {
    console.log('Generating Prisma client...');
    execSync('npm run db:generate', { stdio: 'inherit' });
    
    console.log('\nPushing database schema...');
    execSync('npm run db:push', { stdio: 'inherit' });
    
    console.log('\nSeeding initial data...');
    execSync('npm run db:seed', { stdio: 'inherit' });
    
    console.log('✅ Database setup completed successfully!');
  } catch (error) {
    console.error('❌ Database setup failed:', error.message);
    console.log('Please run the following commands manually:');
    console.log('  npm run db:generate');
    console.log('  npm run db:push');
    console.log('  npm run db:seed');
  }
}

async function createFirstUser() {
  console.log('\n👤 Creating first admin user...\n');
  
  const userName = await askQuestion('Enter admin user name: ', 'System Administrator');
  const userEmail = await askQuestion('Enter admin email: ', 'admin@youruniversity.edu');
  const userPassword = await askQuestion('Enter admin password: ', 'admin123');
  
  const createUserScript = `
const { PrismaClient } = require('@prisma/client');
const bcrypt = require('bcryptjs');

async function createAdmin() {
  const prisma = new PrismaClient();
  
  try {
    const hashedPassword = await bcrypt.hash('${userPassword}', 10);
    
    const user = await prisma.user.create({
      data: {
        name: '${userName}',
        email: '${userEmail}',
        password: hashedPassword,
        role: 'ADMIN',
        isFirstLogin: false
      }
    });
    
    console.log('✅ Admin user created successfully!');
    console.log('Email:', user.email);
    console.log('Password:', '${userPassword}');
    console.log('\\nPlease change the password after first login.');
    
  } catch (error) {
    console.error('❌ Failed to create admin user:', error.message);
  } finally {
    await prisma.$disconnect();
  }
}

createAdmin();
`;

  fs.writeFileSync('create-admin.js', createUserScript);
  
  try {
    execSync('node create-admin.js', { stdio: 'inherit' });
    fs.unlinkSync('create-admin.js'); // Clean up
  } catch (error) {
    console.error('❌ Failed to create admin user:', error.message);
    console.log('You can create the admin user manually through the application.');
  }
}

async function showNextSteps() {
  console.log('\n🎉 Setup completed successfully!\n');
  console.log('Next steps:');
  console.log('1. Start the development server: npm run dev');
  console.log('2. Open http://localhost:3000 in your browser');
  console.log('3. Log in with your admin credentials');
  console.log('4. Set up academic programs and scholarship funds');
  console.log('5. Create student accounts or enable student registration');
  console.log('6. Configure scholarship definitions and criteria');
  console.log('7. Set up bank accounts for disbursements');
  console.log('\n📚 Documentation:');
  console.log('- README.md - System overview and features');
  console.log('- SCHOLARSHIP_IMPLEMENTATION_SUMMARY.md - Technical details');
  console.log('\n💡 Tips:');
  console.log('- Enable Firebase authentication for production');
  console.log('- Set up UploadThing for file uploads');
  console.log('- Configure email settings for notifications');
  console.log('- Review FERPA compliance settings');
  console.log('\nHappy scholarship management! 🎓');
}

async function main() {
  try {
    await setupEnvironment();
    
    const setupDb = await askQuestion('\nWould you like to set up the database now? (y/n): ', 'y');
    if (setupDb.toLowerCase() === 'y' || setupDb.toLowerCase() === 'yes') {
      await setupDatabase();
    }
    
    const createUser = await askQuestion('\nWould you like to create the first admin user? (y/n): ', 'y');
    if (createUser.toLowerCase() === 'y' || createUser.toLowerCase() === 'yes') {
      await createFirstUser();
    }
    
    await showNextSteps();
    
  } catch (error) {
    console.error('❌ Setup failed:', error.message);
  } finally {
    rl.close();
  }
}

// Check if required dependencies are installed
try {
  require('@prisma/client');
  require('bcryptjs');
} catch (error) {
  console.error('❌ Missing dependencies. Please run "npm install" first.');
  process.exit(1);
}

main();
